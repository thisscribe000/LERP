-- LERP (LoveWorld Export Readiness Program) Database Schema
-- Supabase PostgreSQL Schema & Security Policies

CREATE TABLE IF NOT EXISTS public.registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  full_name TEXT NOT NULL,
  kingschat_id TEXT NOT NULL,
  phone_number TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  country TEXT NOT NULL,
  state_province TEXT NOT NULL,
  city TEXT NOT NULL,
  church_ministry_centre TEXT NOT NULL,
  zone_group_church TEXT NOT NULL,
  business_name TEXT,
  industry_category TEXT NOT NULL,
  products_services TEXT NOT NULL,
  assessment_answers JSONB NOT NULL DEFAULT '[]'::jsonb,
  assessment_score INTEGER,
  assessment_result TEXT
);

-- Performance Indexes
CREATE INDEX IF NOT EXISTS idx_registrations_email ON public.registrations(email);
CREATE INDEX IF NOT EXISTS idx_registrations_created_at ON public.registrations(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_registrations_assessment_result ON public.registrations(assessment_result);

-- Grant privileges to API roles
GRANT ALL ON public.registrations TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- Enable Row Level Security (RLS)
ALTER TABLE public.registrations ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if re-running
DROP POLICY IF EXISTS "Allow public insert to registrations" ON public.registrations;
DROP POLICY IF EXISTS "Allow public select for registrations" ON public.registrations;

-- Policy 1: Allow public / anon visitors to submit registrations
CREATE POLICY "Allow public insert to registrations"
  ON public.registrations
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

-- Policy 2: Allow reading registrations for the admin portal queries
CREATE POLICY "Allow public select for registrations"
  ON public.registrations
  FOR SELECT
  TO anon, authenticated
  USING (true);
